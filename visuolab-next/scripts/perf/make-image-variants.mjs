// Makes smaller copies of the site's pictures so a phone does not download a desktop-sized file.
//   public/assets/cases/aster.webp  ->  aster-480w.webp, aster-800w.webp, ...   (never larger than the original, same look)
// and writes src/lib/image-variants.generated.ts, which the pages read to build srcset. The originals are untouched and stay the fallback.
// Run again after adding or replacing a picture in public/assets:  node scripts/perf/make-image-variants.mjs
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(import.meta.dirname, "..", "..");
const ASSETS = path.join(ROOT, "public", "assets");
const WIDTHS = [128, 320, 480, 640, 800, 1024, 1280, 1600];
const MIN_BYTES = 6000; // below this a variant saves nothing worth a request
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));

const manifest = {};
let saved = 0;
for (const file of walk(ASSETS).filter((f) => f.endsWith(".webp") && !/-\d+w\.webp$/.test(f)).sort()) {
  const rel = "/assets/" + path.relative(ASSETS, file).split(path.sep).join("/");
  const meta = await sharp(file).metadata();
  const bytes = fs.statSync(file).size;
  if (bytes < MIN_BYTES || !meta.width) continue;
  const list = [];
  for (const w of WIDTHS) {
    if (w >= meta.width * 0.9) continue; // would be (almost) the original: not worth a second file
    const out = file.replace(/\.webp$/, `-${w}w.webp`);
    const info = await sharp(file).resize({ width: w, withoutEnlargement: true }).webp({ quality: 80, effort: 5, smartSubsample: true }).toFile(out);
    list.push([w, rel.replace(/\.webp$/, `-${w}w.webp`), info.size]);
  }
  list.push([meta.width, rel, bytes]);
  manifest[rel] = list;
  saved += list.length > 1 ? bytes - list[0][2] : 0;
}
const body = Object.fromEntries(Object.entries(manifest).map(([k, v]) => [k, v.map(([w, u]) => [w, u])]));
fs.writeFileSync(path.join(ROOT, "src", "lib", "image-variants.generated.ts"), `/* Generated by scripts/perf/make-image-variants.mjs. Do not edit. [width, address] pairs, smallest first; the last is the original. */\nexport const IMAGE_VARIANTS: Record<string, [number, string][]> = ${JSON.stringify(body, null, 1)};\n`);
for (const [k, v] of Object.entries(manifest)) console.log(k.padEnd(50), v.map(([w, , s]) => `${w}w:${Math.round(s / 1024)}K`).join("  "));
