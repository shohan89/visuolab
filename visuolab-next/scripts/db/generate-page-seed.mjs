// Generates db/seed/pages.sql: the 9 pages and 35 sections of the page CMS, from the typed defaults (src/lib/cms/defaults.ts).
//
//   node --no-warnings scripts/db/generate-page-seed.mjs
//
// Every section goes through checkSection() first, so the file can only contain content that passes its schema, and the references
// (page_section_refs) are the ones the content holds. The output is deterministic (fixed times, readable ids).
//
// The statements are INSERT OR IGNORE: running the file again never overwrites a page or section an editor has changed, and it adds
// any section that is missing. To go back to the defaults on purpose, delete the rows first (DELETE FROM pages; cascades to the rest).
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const imp = (p) => import(pathToFileURL(join(ROOT, p)).href);
const { TEMPLATES, TEMPLATE_NAMES, SECTION_TYPES, checkSection } = await imp("src/lib/cms/registry.ts");
const { PAGE_DEFAULTS } = await imp("src/lib/cms/defaults.ts");

const AT = "2026-10-08T00:00:00.000Z";
const q = (v) => (v === null || v === undefined ? "NULL" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const rows = [];
let sections = 0, refs = 0;

for (const t of TEMPLATE_NAMES) {
  const pageId = `page_${t}`;
  rows.push(`INSERT OR IGNORE INTO pages (id, slug, title, status, template, created_at, updated_at) VALUES (${[pageId, t.replace(/_/g, "-"), TEMPLATES[t].label, "published", t, AT, AT].map(q).join(", ")});`);
  TEMPLATES[t].sections.forEach((slot, position) => {
    const r = checkSection(t, slot.key, PAGE_DEFAULTS[t][slot.key]);
    if (!r.ok) throw new Error(`${t}.${slot.key} does not pass its schema: ${JSON.stringify(r.errors)}`);
    const id = `sec_${t}_${slot.key}`;
    rows.push(`INSERT OR IGNORE INTO page_sections (id, page_id, section_key, section_type, position, is_enabled, content, schema_version, created_at, updated_at) VALUES (${[id, pageId, slot.key, slot.type, position, 1, JSON.stringify(r.content), SECTION_TYPES[slot.type].version, AT, AT].map(q).join(", ")});`);
    sections++;
    for (const ref of r.refs) {
      rows.push(`INSERT OR IGNORE INTO page_section_refs (section_id, field_path, kind, media_id, case_study_id) VALUES (${[id, ref.path, ref.kind, ref.kind === "media" ? ref.id : null, ref.kind === "case_study" ? ref.id : null].map(q).join(", ")});`);
      refs++;
    }
  });
}

const header = `-- Pages and sections of the page CMS. GENERATED by scripts/db/generate-page-seed.mjs from src/lib/cms/defaults.ts: edit the defaults, not this file.
--
-- INSERT OR IGNORE: safe to run again; it never overwrites content an editor has saved, and it adds sections that are missing.
-- It needs the content seed (media and case studies, db/seed/content.sql) and migration 0016.

`;
mkdirSync(join(ROOT, "db", "seed"), { recursive: true });
writeFileSync(join(ROOT, "db", "seed", "pages.sql"), header + rows.join("\n") + "\n");
console.log(`pages: ${TEMPLATE_NAMES.length}, page_sections: ${sections}, page_section_refs: ${refs}`);
